"""ASS subtitle generation that mirrors the canvas preview
(frontend/src/editor/subtitles/renderSubtitles.ts).

Layout model shared with the preview:
* the page text is one line anchored at its centre (``\\an5``) at
  ``style.position`` (normalised to the reference frame);
* glyph em size == ``style.fontSize`` (converted with the font's ``assRatio``);
* outline = ``\\bord`` (canvas: stroke of 2x width under the fill, round joins);
* hard shadow = ``\\shad`` (union of fill + outline, shifted);
* the box is a rounded-rect drawing on layer 0 sized from the measured text;
* karaoke / word pop are emitted as one event per active-word slice.
"""

from __future__ import annotations

from pathlib import Path

from ..schemas import Cut, Line, SubtitleStyle
from . import timeline as tl
from .fonts import FontFace, resolve_face, text_width

KAPPA = 0.5523


def ass_color(hex_color: str) -> str:
    h = hex_color.lstrip("#")
    r, g, b = h[0:2], h[2:4], h[4:6]
    return f"&H{b}{g}{r}&".upper()


def ass_alpha(opacity: float) -> str:
    return f"&H{round((1 - tl.clamp01(opacity)) * 255):02X}&"


def ass_time(t: float) -> str:
    cs = max(0, int(round(t * 100)))
    h, rem = divmod(cs, 360000)
    m, rem = divmod(rem, 6000)
    s, cs = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def escape(text: str) -> str:
    return text.replace("\\", "/").replace("{", "(").replace("}", ")").replace("\n", " ")


def _f(v: float) -> str:
    """Compact float for tags."""
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return s if s not in ("", "-0") else "0"


def rounded_rect(w: float, h: float, r: float) -> str:
    r = max(0.0, min(r, w / 2, h / 2))
    if r < 0.5:
        return f"m 0 0 l {_f(w)} 0 {_f(w)} {_f(h)} 0 {_f(h)}"
    k = r * KAPPA
    return (
        f"m {_f(r)} 0 l {_f(w - r)} 0 b {_f(w - r + k)} 0 {_f(w)} {_f(r - k)} {_f(w)} {_f(r)} "
        f"l {_f(w)} {_f(h - r)} b {_f(w)} {_f(h - r + k)} {_f(w - r + k)} {_f(h)} {_f(w - r)} {_f(h)} "
        f"l {_f(r)} {_f(h)} b {_f(r - k)} {_f(h)} 0 {_f(h - r + k)} 0 {_f(h - r)} "
        f"l 0 {_f(r)} b 0 {_f(r - k)} {_f(r - k)} 0 {_f(r)} 0"
    )


def _anim_tags(style: SubtitleStyle, page_start: float, seg_start: float, x: float, y: float, fit: float = 1.0) -> str:
    """Line appearance animation, continued from the slice start (exact for linear ramps).
    ``fit`` is the static auto-fit scale (see timeline.fit_scale)."""
    alpha, scale, dy = tl.line_anim_state(style, page_start, seg_start)
    remaining = max(0.0, page_start + tl.LINE_ANIM - seg_start)
    ms = int(round(remaining * 1000))
    tags = []
    if style.animation == "slide" and ms > 0:
        tags.append(f"\\move({_f(x)},{_f(y + dy)},{_f(x)},{_f(y)},0,{ms})")
    else:
        tags.append(f"\\pos({_f(x)},{_f(y)})")
    if style.animation != "none" and ms > 0:
        a1 = round((1 - alpha) * 255)
        tags.append(f"\\fade({a1},0,0,0,{ms},{ms},{ms})")
    if style.animation == "pop" and ms > 0:
        s0, s1 = _f(scale * fit * 100), _f(fit * 100)
        tags.append(f"\\fscx{s0}\\fscy{s0}\\t(0,{ms},\\fscx{s1}\\fscy{s1})")
    elif fit < 0.9999:
        tags.append(f"\\fscx{_f(fit * 100)}\\fscy{_f(fit * 100)}")
    return "".join(tags)


def build_ass(
    lines: list[Line],
    cuts: list[Cut],
    style: SubtitleStyle,
    frame: tuple[int, int],
    fonts_dir: Path | None = None,
) -> str:
    """Return a complete .ass document for the reference frame ``frame``."""
    width, height = frame
    face: FontFace = resolve_face(style.fontFamily, style.fontWeight, fonts_dir)
    base_size = face.ass_size(style.fontSize)
    x, y = style.position.x * width, style.position.y * height
    shadow_on = style.shadowOpacity > 0.001 and style.shadowOffset > 0
    header = [
        "[Script Info]",
        "; Generated by Bannerka",
        "ScriptType: v4.00+",
        f"PlayResX: {width}",
        f"PlayResY: {height}",
        "WrapStyle: 2",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: None",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, "
        "Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, "
        "MarginL, MarginR, MarginV, Encoding",
        "Style: Text,{font},{size},{c1}{a1},&H00FFFFFF,{c3}{a3},{c4}{a4},0,0,0,0,100,100,0,0,1,{bord},{shad},5,0,0,0,1".format(
            font=face.internal_name,
            size=_f(base_size),
            c1="&H00" + ass_color(style.color)[2:-1],
            a1="",
            c3="&H00" + ass_color(style.outlineColor)[2:-1],
            a3="",
            c4="&H" + ass_alpha(style.shadowOpacity)[2:-1] + ass_color(style.shadowColor)[2:-1],
            a4="",
            bord=_f(style.outlineWidth),
            shad=_f(style.shadowOffset if shadow_on else 0),
        ),
        f"Style: Box,{face.internal_name},{_f(base_size)},&H00FFFFFF,&H00FFFFFF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,5,0,0,0,1",
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    events: list[str] = []
    color = ass_color(style.color)
    hl = ass_color(style.highlightColor)
    for page in tl.build_pages(lines, cuts, style):
        text_w = text_width(face, page.text, style.fontSize)
        fit = tl.fit_scale(text_w, style, width)
        if style.box.enabled:
            bw = text_w + 2 * style.box.paddingX
            bh = face.line_height(style.fontSize) + 2 * style.box.paddingY
            tags = _anim_tags(style, page.start, page.start, x, y, fit)
            events.append(
                f"Dialogue: 0,{ass_time(page.start)},{ass_time(page.end)},Box,,0,0,0,,"
                f"{{\\an5{tags}\\bord0\\shad0\\1c{ass_color(style.box.color)}\\1a{ass_alpha(style.box.opacity)}\\p1}}"
                f"{rounded_rect(bw, bh, style.box.radius)}{{\\p0}}"
            )
        for seg_start, seg_end, active in tl.segments(page, style):
            parts = []
            for i, w in enumerate(page.words):
                word = escape(w.text)
                if i == active:
                    on = []
                    if style.karaoke:
                        on.append(f"\\1c{hl}")
                    if style.wordPop:
                        s0 = tl.word_scale(style, w.start, seg_start)
                        on.append(f"\\fs{_f(base_size * s0)}")
                        ms = int(round(max(0.0, w.start + tl.WORD_POP_DUR - seg_start) * 1000))
                        if ms > 0:
                            on.append(f"\\t(0,{ms},\\fs{_f(base_size * tl.WORD_POP)})")
                    off = (f"\\1c{color}" if style.karaoke else "") + (f"\\fs{_f(base_size)}" if style.wordPop else "")
                    parts.append(f"{{{''.join(on)}}}{word}{{{off}}}")
                else:
                    parts.append(word)
                if i < len(page.words) - 1:
                    parts.append(" ")
            tags = _anim_tags(style, page.start, seg_start, x, y, fit)
            events.append(
                f"Dialogue: 1,{ass_time(seg_start)},{ass_time(seg_end)},Text,,0,0,0,,"
                f"{{\\an5\\q2{tags}}}{''.join(parts)}"
            )
    return "\n".join(header + events) + "\n"
